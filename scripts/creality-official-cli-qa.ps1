<#
Windows-only opt-in regression of the signed Creality Print 7.3 CLI.
It reads disposable converted 3MF files, never detects or connects a printer.
Run with -VerifyOnly to check existing G-code without re-slicing.
#>
param(
    [Parameter(Mandatory=$true)][string]$SlicerExe,
    [Parameter(Mandatory=$true)][string]$FixtureManifest,
    [Parameter(Mandatory=$true)][string]$InputDir,
    [Parameter(Mandatory=$true)][string]$OutputDir,
    [switch]$VerifyOnly
)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
if ($env:OS -ne 'Windows_NT') { throw 'Official Creality Print CLI QA requires Windows.' }
if (!(Test-Path -LiteralPath $SlicerExe -PathType Leaf)) { throw 'Creality Print executable not found.' }
if (!(Test-Path -LiteralPath $FixtureManifest -PathType Leaf)) { throw 'QA fixture manifest missing.' }
$spec=Get-Content -LiteralPath $FixtureManifest -Raw -Encoding UTF8 | ConvertFrom-Json
if ($spec.schema -ne 'slicebridge.creality.cli-fixtures.v1' -or @($spec.cases).Count -ne 5) {
    throw 'Unexpected QA target manifest; fail closed.'
}
$binary=Get-Item -LiteralPath $SlicerExe
$signature=Get-AuthenticodeSignature -FilePath $binary.FullName
if ($signature.Status -ne 'Valid' -or $binary.VersionInfo.CompanyName -ne 'CREALITY' -or
    $binary.VersionInfo.ProductVersion -ne [string]$spec.slicerVersion) {
    throw 'Slicer signature, publisher, or official verified build version mismatch.'
}
$inputRoot=[IO.Path]::GetFullPath($InputDir)
$outputRoot=[IO.Path]::GetFullPath($OutputDir)
if ($outputRoot.TrimEnd('\') -eq $inputRoot.TrimEnd('\')) { throw 'Output must be separate from source fixtures.' }
[IO.Directory]::CreateDirectory($outputRoot) | Out-Null
$results=@()
foreach ($case in $spec.cases) {
    $name=[string]$case.name
    if ($name -notmatch '^Creality-[A-Za-z0-9.-]+(?:-[A-Za-z0-9.-]+)*-QA$') {
        throw ("Unsafe fixture name: "+$name)
    }
    $source=Join-Path $inputRoot ($name+'.3mf')
    if (!(Test-Path -LiteralPath $source -PathType Leaf)) { throw ("QA 3MF missing: "+$name) }
    $sourceSha=(Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash
    if ($sourceSha -ne [string]$case.sourceSHA256) { throw ("Converted 3MF checksum mismatch: "+$name) }
    $targetDir=Join-Path $outputRoot $name
    [IO.Directory]::CreateDirectory($targetDir) | Out-Null
    $output=Join-Path $targetDir 'plate_1.gcode'
    if (!$VerifyOnly) {
        if (Test-Path -LiteralPath $output) { throw ("Refusing to overwrite QA G-code: "+$output) }
        $sandbox=Join-Path $targetDir 'sandbox'
        foreach ($relative in @('','Roaming','Local','Temp')) {
            $path=if ($relative) {Join-Path $sandbox $relative} else {$sandbox}
            [IO.Directory]::CreateDirectory($path) | Out-Null
        }
        $psi=New-Object System.Diagnostics.ProcessStartInfo
        $psi.FileName=$binary.FullName
        $psi.Arguments='--cli --slice 0 --need-gcode-file --outputdir "'+$targetDir+'" "'+$source+'"'
        $psi.WorkingDirectory=$targetDir
        $psi.UseShellExecute=$false
        $psi.CreateNoWindow=$true
        $psi.RedirectStandardOutput=$true
        $psi.RedirectStandardError=$true
        $psi.EnvironmentVariables['USERPROFILE']=$sandbox
        $psi.EnvironmentVariables['HOME']=$sandbox
        $psi.EnvironmentVariables['APPDATA']=Join-Path $sandbox 'Roaming'
        $psi.EnvironmentVariables['LOCALAPPDATA']=Join-Path $sandbox 'Local'
        $psi.EnvironmentVariables['TEMP']=Join-Path $sandbox 'Temp'
        $psi.EnvironmentVariables['TMP']=Join-Path $sandbox 'Temp'
        $psi.EnvironmentVariables['CREALITY_PRINT_PROFILE_DIR']=Join-Path $sandbox 'Profiles'
        $proc=New-Object System.Diagnostics.Process
        $proc.StartInfo=$psi
        if (!$proc.Start()) { throw ("Creality CLI failed to start for "+$name) }
        $stdoutTask=$proc.StandardOutput.ReadToEndAsync()
        $stderrTask=$proc.StandardError.ReadToEndAsync()
        if (!$proc.WaitForExit(90000)) {
            $proc.Kill()
            throw ("Creality CLI QA timed out; its exact PID was stopped for "+$name)
        }
        [IO.File]::WriteAllText((Join-Path $targetDir 'stdout.log'),$stdoutTask.Result)
        [IO.File]::WriteAllText((Join-Path $targetDir 'stderr.log'),$stderrTask.Result)
        if ($proc.ExitCode -ne 0) { throw ("Creality CLI nonzero exit for "+$name+" : "+$proc.ExitCode) }
    }
    if (!(Test-Path -LiteralPath $output -PathType Leaf) -or (Get-Item $output).Length -lt 12000) {
        throw ("Missing or too-small native G-code: "+$name)
    }
    $lines=[IO.File]::ReadAllLines($output)
    if ($lines.Count -lt 200 -or $lines[1] -notmatch 'generated by Creality_Print V7\.3\.0\.6157') {
        throw ("Not official Creality Print 7.3 G-code: "+$name)
    }
    $config=@{}
    foreach ($key in @('printer_model','printer_settings_id','nozzle_diameter',
            'retraction_distances_when_cut','long_retractions_when_cut',
            'enable_long_retraction_when_cut','print_settings_id')) {
        $prefix='; '+$key+' = '
        $value=$lines | Where-Object {$_.StartsWith($prefix)} | Select-Object -First 1
        if (!$value) { throw ("Missing G-code setting "+$key+": "+$name) }
        $config[$key]=$value.Substring($prefix.Length)
    }
    if ($config['printer_model'] -ne [string]$case.model -or
        $config['printer_settings_id'] -ne ([string]$case.model+' '+[string]$case.nozzle+' nozzle') -or
        $config['nozzle_diameter'] -ne [string]$case.nozzle -or
        $config['retraction_distances_when_cut'] -ne [string]$case.cut -or
        $config['long_retractions_when_cut'] -ne '1' -or
        $config['enable_long_retraction_when_cut'] -ne '2') {
        throw ("Native printer/nozzle or active manufacturer cut settings differ: "+$name)
    }
    $motions=@($lines | Where-Object {$_ -match '^G[01](\s|$)'}).Count
    $extrusions=@($lines | Where-Object {$_ -match '^G1\s' -and $_ -match '\bE[-+]?[0-9.]+'}).Count
    $bambuMacros=@($lines | Where-Object {$_ -match '^M62[01](\s|$)'}).Count
    if ($motions -le 100 -or $extrusions -le 50 -or $bambuMacros -ne 0) {
        throw ("No meaningful native toolpath, or Bambu-only macros leaked: "+$name)
    }
    $hash=(Get-FileHash -LiteralPath $output -Algorithm SHA256).Hash
    $results+=@{target=$name;source3mfSHA256=$sourceSha;gcodeSHA256=$hash;
        physicalNozzleMM=[string]$case.nozzle;manufacturerCutDistanceMM=[string]$case.cut;
        printerModel=[string]$case.model;gcodeBytes=(Get-Item $output).Length;
        motionCommands=$motions;extrusionCommands=$extrusions;config=$config;
        slicer='Official signed Creality Print 7.3.0.6157 Windows CLI';
        noHardwarePrint=$true;sourceModified=$false}
    Write-Output ("QA_VERIFIED "+$name+" nozzle="+$case.nozzle+" cutMM="+$case.cut+" motions="+$motions+" extrusions="+$extrusions+" SHA256="+$hash)
}
$qaReport=@{schema='slicebridge.creality.official-cli-qa.v1';head=[string]$spec.head;
    mode=if($VerifyOnly){'verify-existing'}else{'native-cli-slice'};
    targets=$results;verified=$results.Count;physicalPrints=0;
    note='Software G-code verification only. No multicolor/CFS or hardware approval.'}
$qaReport | ConvertTo-Json -Depth 7 | Set-Content -Path (Join-Path $outputRoot 'qa-validation.json') -Encoding UTF8
Write-Output ("QA_ALL_FIVE_PASS "+$results.Count)
