def _local(tag):
    return tag.rsplit("}", 1)[-1]


def fixture_paths():
    return sorted(FIXTURES.glob("*.3mf"))


def structure_problems(path):
    """ZIP and package-shell defects, as strings. An empty list means the shell is sound."""
    problems = []
    try:
        archive = zipfile.ZipFile(path)
    except (zipfile.BadZipFile, OSError) as exc:
        return ["not a readable ZIP: %s" % exc]
    with archive:
        infos = archive.infolist()
        names = [i.filename for i in infos]
        if len(names) != len(set(names)):
            problems.append("duplicate entry names")
        for info in infos:
            name = info.filename
            parts = name.split("/")
            if name.startswith("/") or "\\" in name or ".." in parts or ":" in parts[0]:
                problems.append("unsafe entry name: %s" % name)
            if info.flag_bits & 0x1:
                problems.append("encrypted entry: %s" % name)
        if "[Content_Types].xml" not in names:
            problems.append("missing [Content_Types].xml")
        if "_rels/.rels" not in names:
            problems.append("missing _rels/.rels")
            return problems
        try:
            rels = ET.fromstring(archive.read("_rels/.rels"))
        except ET.ParseError as exc:
            return problems + ["invalid _rels/.rels: %s" % exc]
        targets = [r.get("Target", "").lstrip("/") for r in rels
                   if _local(r.tag) == "Relationship" and r.get("Type", "").endswith(MODEL_REL_SUFFIX)]
        if not targets:
            problems.append("no 3D model relationship in _rels/.rels")
        for target in targets:
            if target not in names:
                problems.append("model relationship target missing: %s" % target)
        if MODEL_PART in names:
            try:
                ET.fromstring(archive.read(MODEL_PART))
            except ET.ParseError as exc:
                problems.append("invalid %s: %s" % (MODEL_PART, exc))
    return problems


def facts(path):
    """Counts and settings read from one source 3MF. Raises on unreadable XML or JSON."""
    with zipfile.ZipFile(path) as archive:
        names = archive.namelist()
        root = ET.fromstring(archive.read(MODEL_PART))
        vertices = sum(1 for el in root.iter() if _local(el.tag) == "vertex")
        triangles = [el for el in root.iter() if _local(el.tag) == "triangle"]
        paint = Counter()
        for tri in triangles:
            for key, value in tri.attrib.items():
                if _local(key) in PAINT_ATTRS:
                    paint[value.strip().upper()] += 1
        objects = [el for el in root.iter() if _local(el.tag) == "object"]
        build_items = [el for el in root.iter() if _local(el.tag) == "item"]
        extruders = []
        if "Metadata/model_settings.config" in names:
            config = ET.fromstring(archive.read("Metadata/model_settings.config"))
            extruders = [el.get("value") for el in config.iter()
                         if _local(el.tag) == "metadata" and el.get("key") == "extruder"]
        project = {}
        if "Metadata/project_settings.config" in names:
            project = json.loads(archive.read("Metadata/project_settings.config").decode("utf-8"))
        nozzle = project.get("nozzle_diameter")
        return {
            "names": sorted(names),
            "gcode": sorted(n for n in names if n.endswith(GCODE_SUFFIXES)),
            "objects": len(objects),
            "build_items": len(build_items),
            "vertices": vertices,
            "triangles": len(triangles),
            "paint": dict(sorted(paint.items())),
            "extruders": extruders,
            "printer_model": project.get("printer_model"),
            "nozzle": nozzle,
            "filament_colours": project.get("filament_colour", []),
            "filament_types": project.get("filament_type", []),
        }
